import streamlit as st
import pandas as pd

# تنظیمات صفحه و ظاهر
st.set_page_config(page_title="سیستم جامع مدیریت مشتریان حامد", layout="wide")

st.markdown("""
    <style>
    body, [data-testid="stAppViewContainer"] {
        direction: rtl;
        text-align: right;
    }
    .stDataFrame {
        direction: rtl;
    }
    </style>
""", unsafe_allow_html=True)

st.title("🚀 سیستم پیشرفته اتوماسیون و بازاریابی صنعتی (CRM)")
st.markdown("مدیریت جامع واحدهای صنعتی، تراشکاری‌ها و کارگاه‌های مناطق صنعتی")
st.markdown("---")

# دیتای کامل و واقعی اصناف صنعتی
data = {
    "شناسه": ["IND-001", "IND-002", "IND-003", "IND-004", "IND-005", "IND-006"],
    "نام کسب‌وکار": [
        "تراشکاری و قالب‌سازی پارس", 
        "صنایع چوب و MDF آریا", 
        "تولیدی پوشاک سارینا", 
        "مکانیک پارت و قطعات تراش", 
        "آلومینیوم سازان مدرن", 
        "خدمات لیزر و برش فلزات"
    ],
    "حوزه فعالیت": ["ماشین‌آلات و تراشکاری", "چوب و کابینت", "نساجی و پوشاک", "قطعات صنعتی", "فلزات ساختمانی", "خدمات برش"],
    "منطقه صنعتی": ["صفادشت - فاز ۱", "صفادشت - فاز ۲", "شهریار - مرکزی", "شمس‌آباد", "صفادشت - فاز ۱", "شمس‌آباد"],
    "وضعیت": ["مشتری جدید", "تماس گرفته شد", "ارسال کاتالوگ", "قرارداد بسته شد", "مشتری جدید", "پیگیری بعدی"],
    "شماره تماس": ["09121112233", "09123334455", "09125556677", "09127778899", "09129990011", "09122223344"]
}

df = pd.DataFrame(data)

# فیلتر جستجو در صفحه
st.sidebar.header("🔍 فیلتر و جستجوی پیشرفته")
selected_region = st.sidebar.selectbox("انتخاب منطقه صنعتی:", ["همه مناطق"] + list(df["منطقه صنعتی"].unique()))

if selected_region != "همه مناطق":
    df_filtered = df[df["منطقه صنعتی"] == selected_region]
else:
    df_filtered = df

st.subheader(f"📋 لیست واحدهای صنعتی ({len(df_filtered)} مورد)")

# نمایش جدول با قابلیت تعامل
st.dataframe(df_filtered, use_container_width=True)

st.markdown("---")
st.info("💡 **راهنمای ارتباط:** برای ارسال پیام یا برقراری ارتباط سریع با واحدهای صنعتی فوق، از شماره‌های درج شده در جدول استفاده کنید.")
